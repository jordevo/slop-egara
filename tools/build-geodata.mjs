// tools/build-geodata.mjs — writes js/terrassa-geodata.js (see geo-base.mjs for the frame and the data sources)
// usage: GEO_DATA=tools/data/terrassa node --max-old-space-size=8192 tools/build-geodata.mjs [out.js]
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { geo, log, centroid, cleanRing } from './geo-base.mjs';
import { roadLines, buildRoadGraph } from './geo-roads.mjs';
import { landRing, SIDEWALK } from './geo-blocks.mjs';
import { blocks } from './geo-buildings.mjs';
import { landuse, parks, trees, water, rail, landmarks, places, squares, region, shops } from './geo-features.mjs';

const OUT = process.argv[2] || fileURLToPath(new URL('../js/terrassa-geodata.js', import.meta.url));
const q = (v) => Math.round(v * 10) / 10;
const flat = (pts) => pts.flatMap(([x, z]) => [q(x), q(z)]);

// Neighbourhoods: every block goes to the nearest place node (HOW_TO_IMPROVE.md §2.6)
const districts = places.map((p) => ({ name: p.name, x: q(p.xz[0]), z: q(p.xz[1]) }));
const districtOf = (x, z) => {
  let best = -1, bd = Infinity;
  districts.forEach((d, i) => { const dd = Math.hypot(d.x - x, d.z - z); if (dd < bd) { bd = dd; best = i; } });
  return best;
};
for (const b of blocks) {
  const [cx, cz] = centroid(b.poly);
  b.district = districtOf(cx, cz);
}

const lb = (() => { let x0 = Infinity, x1 = -Infinity, z0 = Infinity, z1 = -Infinity; for (const [x, z] of landRing) { x0 = Math.min(x0, x); x1 = Math.max(x1, x); z0 = Math.min(z0, z); z1 = Math.max(z1, z); } return { minX: q(x0), maxX: q(x1), minZ: q(z0), maxZ: q(z1) }; })();

const GEO = {
  version: 2,
  city: 'Terrassa',
  frame: { bearingDeg: Math.round((geo.THETA * 180) / Math.PI * 100) / 100, origin: 'Plaça Vella (centre)', lat0: 41.561974, lon0: 2.011102, units: 'm', cutZ: lb.minZ, sidewalk: SIDEWALK, detail: geo.DETAIL },
  land: flat(landRing),
  bounds: lb,
  municipality: geo.terrassa.rings.map(flat),
  municipalities: geo.municipalities.filter((m) => m.name !== 'Terrassa').map((m) => ({ name: m.name, population: m.population, rings: m.rings.map((r) => flat(cleanRing(r, 10))) })),
  // [name, curb-to-curb width, direction (1 along, -1 against, 0 both), lanes, class (0 street, 1 motorway/trunk, 2 primary/secondary, 3 pedestrian/living, 4 service), flat pts]
  roads: roadLines.map((r) => [r.name, q(r.w), r.dir, r.lanes, r.cls, flat(r.pts)]),
  // Street centreline graph: nodes [x, z, ...], links [a, b, name index, width, lanes, dir, inner pts, class, bridge, roundabout],
  // signals / stops: node indices, crossings [x, z, ux, uz, width, kind]
  roadGraph: buildRoadGraph(),
  // [outline, lot rects, park share, park name, rectangular, frames | 0, land-use class, class share, district, buildings, cover, land-use shares]
  blocks: blocks.map((b) => [flat(b.poly), b.rects.map((r) => r.map(q)), Math.round(b.park * 100) / 100, b.parkName, b.rect ? 1 : 0,
    b.frames ? b.frames.map(([th, px, pz, rs]) => [Math.round(th * 1e4) / 1e4, q(px), q(pz), rs.map((r) => r.map(q))]) : 0,
    b.cls, Math.round(b.clsShare * 100) / 100, b.district, b.buildings, b.cover, b.shares]),
  parks: parks.map((p) => ({ name: p.name, cls: p.cls, area: p.area, rings: p.rings.map(flat) })),
  landuse: landuse.filter((l) => l.area >= 400).map((l) => ({ cls: l.cls, name: l.name, area: Math.round(l.area), rings: [flat(cleanRing(l.outer, 1.5)), ...l.inners.map((r) => flat(cleanRing(r, 1.5)))] })),
  water: water.map((w) => ({ name: w.name, w: q(w.w), pts: flat(w.pts) })),
  rail: rail.map((r) => ({ name: r.name, bridge: r.bridge, pts: flat(r.pts) })),
  trees: flat(trees),
  landmarks,
  districts,
  squares: squares.map((s) => ({ name: s.name, x: q(s.xz[0]), z: q(s.xz[1]) })),
  // Named shops & businesses: [name, kind (0 shop, 1 bar/restaurant, 2 bank, 3 pharmacy/health, 4 office, 5 hotel, 6 fuel, 7 other), OSM type, x, z]
  shops: shops.map((s) => [s.name, s.kind, s.type, s.x, s.z]),
  region: {
    roads: region.roads.map((r) => [r.name, r.cls, r.link ? 1 : 0, flat(r.pts)]),
    rails: region.rails.map((r) => [r.name, r.narrow ? 1 : 0, flat(r.pts)]),
    settlements: region.settlements.map((s) => ({ name: s.name, cls: s.cls, area: s.area, ring: flat(s.ring) })),
    towns: region.towns,
    peaks: region.peaks
  }
};

const json = JSON.stringify(GEO);
const header = `// js/terrassa-geodata.js — GENERATED by tools/build-geodata.mjs, do not edit by hand.
// Real geography of Terrassa (Vallès Occidental, Catalonia) in the simulation's world frame: 1 unit = 1 m, x = east
// along the Eixample's street grid, z = grid south (north = -z), origin at the centre of the Plaça Vella, axes turned
// ${GEO.frame.bearingDeg}° from true north. Polygons & polylines are flat [x0, z0, x1, z1, ...] arrays.
// Source: © OpenStreetMap contributors (ODbL), downloaded 2026-10-24 via Overpass (tools/data/q_*.overpassql).
// Fidelity notes & how to improve each layer: HOW_TO_IMPROVE.md
`;
fs.writeFileSync(OUT, `${header}export const GEO = ${json};\n`);
log(`wrote ${OUT} (${(fs.statSync(OUT).size / 1024).toFixed(0)} KB)`);
for (const [k, v] of Object.entries(GEO)) log(`  ${k}: ${(JSON.stringify(v).length / 1024).toFixed(0)} KB`);
